class Trajectory(BaseModel):
    """ATIF root document (spec §II Root-Level Metadata)."""

    model_config = ConfigDict(extra="forbid")

    schema_version: Literal["ATIF-v1.7"] = SCHEMA_VERSION
    session_id: str | None = Field(
        default=None,
        description=(
            "Run-scoped identifier (MAY be shared across sibling subagents / continuations). "
            "Optional in v1.7."
        ),
    )
    trajectory_id: str | None = Field(
        default=None,
        description=(
            "Per-document unique id. REQUIRED on embedded subagent entries; optional otherwise (v1.7)."
        ),
    )
    agent: AgentSchema = Field(description="Agent identity.")
    steps: list[StepObject] = Field(description="Sequential trajectory steps.")
    notes: str | None = Field(default=None, description="Developer-facing notes.")
    final_metrics: FinalMetricsSchema | None = Field(
        default=None, description="Aggregate metrics across the trajectory."
    )
    continued_trajectory_ref: str | None = Field(
        default=None,
        description="Reference to a continuation trajectory file (if split).",
    )
    extra: dict[str, Any] | None = None
    subagent_trajectories: list[Trajectory] | None = Field(
        default=None,
        description=(
            "Embedded subagent trajectories. Each entry MUST set trajectory_id; "
            "trajectory_ids within this array MUST be unique (spec §II v1.7)."
        ),
    )

    @model_validator(mode="after")
    def _check_subagent_uniqueness(self) -> Trajectory:
        """Spec §II: every embedded subagent MUST have trajectory_id; ids MUST be unique."""
        if self.subagent_trajectories:
            seen: set[str] = set()
            for child in self.subagent_trajectories:
                if not child.trajectory_id:
                    raise ValueError(
                        "Embedded subagent trajectory MUST set trajectory_id (spec §II v1.7)."
                    )
                if child.trajectory_id in seen:
                    raise ValueError(
                        f"Duplicate trajectory_id {child.trajectory_id!r} in "
                        "subagent_trajectories (spec §II v1.7)."
                    )
                seen.add(child.trajectory_id)
        return self


