class AgentSchema(BaseModel):
    """Agent identity at trajectory root (spec §II AgentSchema)."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(description="Agent system name.")
    version: str = Field(description="Agent system version.")
    model_name: str | None = Field(
        default=None,
        description="Default LLM model for the trajectory (step-level overrides).",
    )
    tool_definitions: list[dict[str, Any]] | None = Field(
        default=None,
        description="OpenAI-style function definitions (each: {type, function}).",
    )
    extra: dict[str, Any] | None = None


class StepObject(BaseModel):
    """One step in the trajectory (spec §II StepObject)."""

    model_config = ConfigDict(extra="forbid")

    step_id: int = Field(description="Ordinal index starting from 1.")
    timestamp: str | None = Field(
        default=None, description="ISO 8601 timestamp (e.g. '2025-10-16T14:30:00Z')."
    )
    source: Literal["system", "user", "agent"] = Field(description="Step originator.")
    model_name: str | None = Field(
        default=None,
        description="Per-step LLM model override. Only on source='agent'.",
    )
    reasoning_effort: str | float | None = Field(
        default=None, description="Effort level (low/medium/high or float). Only on source='agent'."
    )
    message: str | list[ContentPart] = Field(
        description="Dialogue message. May be empty string. Required."
    )
    reasoning_content: str | None = Field(
        default=None, description="Explicit internal reasoning. Only on source='agent'."
    )
    tool_calls: list[ToolCallSchema] | None = Field(
        default=None,
        description="Structured tool calls for this turn. Only on source='agent'.",
    )
    observation: ObservationSchema | None = Field(
        default=None,
        description="Environment feedback / tool results for this step.",
    )
    metrics: MetricsSchema | None = Field(
        default=None, description="LLM metrics. Only on source='agent'."
    )
    extra: dict[str, Any] | None = None
    llm_call_count: int | None = Field(
        default=None,
        description=(
            "Number of LLM inferences this step represents. "
            "1 = normal; >1 = aggregated; 0 on source='agent' = deterministic dispatch "
            "(metrics + reasoning_content MUST be absent). Null = not tracked."
        ),
    )
    is_copied_context: bool | None = Field(
        default=None,
        description=(
            "True iff this step was retained across a compaction boundary "
            "(SFT consumers MUST filter out)."
        ),
    )

    @model_validator(mode="after")
    def _check_agent_only_fields(self) -> StepObject:
        """Spec §II: model_name / reasoning_effort / reasoning_content /
        tool_calls / metrics are agent-only."""
        if self.source != "agent":
            for field_name in (
                "model_name",
                "reasoning_effort",
                "reasoning_content",
                "tool_calls",
                "metrics",
            ):
                if getattr(self, field_name) is not None:
                    raise ValueError(
                        f"StepObject.{field_name} is only applicable when source='agent' "
                        f"(got source={self.source!r})."
                    )
        return self

    @model_validator(mode="after")
    def _check_deterministic_dispatch(self) -> StepObject:
        """Spec §II: llm_call_count=0 on source='agent' ⇒ metrics + reasoning_content absent."""
        if (
            self.source == "agent"
            and self.llm_call_count == 0
            and (self.metrics is not None or self.reasoning_content is not None)
        ):
            raise ValueError(
                "StepObject.llm_call_count=0 on source='agent' (deterministic dispatch) "
                "requires `metrics` and `reasoning_content` to be absent (spec §II)."
            )
        return self


