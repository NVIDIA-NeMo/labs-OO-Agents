"""ATIF v1.7 Pydantic models — schema + serializer + validator.

Mirrors the spec at ``0001-trajectory-format-2.md`` §II "Schema".

These models are the canonical in-memory representation of an ATIF
trajectory. The exporter assembles instances of these, and downstream
consumers (validators, dashboards, SFT pipelines) parse JSON into them
via ``Trajectory.model_validate_json(...)``.

Validation is intentionally structural-only at this layer: schema-level
required fields, enum values, conditional fields (e.g. ``ContentPart``
text vs image, ``SubagentTrajectoryRef`` resolution mechanism).
Normative cross-cutting rules (sequential step_ids, joinability,
context-management boundary semantics, ``is_copied_context``
propagation) are enforced separately in :mod:`tests.atif.test_normative_rules`
and at exporter build-time.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

SCHEMA_VERSION: Literal["ATIF-v1.7"] = "ATIF-v1.7"


# ---------------------------------------------------------------------------
# Leaf schemas
# ---------------------------------------------------------------------------


class ImageSource(BaseModel):
    """Image storage reference for multimodal content (spec §II ImageSourceSchema, v1.6+)."""

    model_config = ConfigDict(extra="forbid")

    media_type: Literal["image/jpeg", "image/png", "image/gif", "image/webp"] = Field(
        description="MIME type of the image."
    )
    path: str = Field(description="Location of the image. Relative path, absolute path, or URL.")


class ContentPart(BaseModel):
    """Multimodal content part (spec §II ContentPartSchema, v1.6+).

    ``type='text'`` requires ``text`` and forbids ``source``;
    ``type='image'`` requires ``source`` and forbids ``text``.
    """

    model_config = ConfigDict(extra="forbid")

    type: Literal["text", "image"] = Field(description="Content kind.")
    text: str | None = Field(default=None, description="Text content (type=text only).")
    source: ImageSource | None = Field(default=None, description="Image source (type=image only).")

    @model_validator(mode="after")
    def _check_conditional_fields(self) -> ContentPart:
        if self.type == "text":
            if self.text is None:
                raise ValueError("ContentPart.type='text' requires `text`")
            if self.source is not None:
                raise ValueError("ContentPart.type='text' must omit `source`")
        else:  # image
            if self.source is None:
                raise ValueError("ContentPart.type='image' requires `source`")
            if self.text is not None:
                raise ValueError("ContentPart.type='image' must omit `text`")
        return self


