# Metrics schemas
# ---------------------------------------------------------------------------


class MetricsSchema(BaseModel):
    """Per-step LLM metrics (spec §II MetricsSchema). All fields optional."""

    model_config = ConfigDict(extra="forbid")

    prompt_tokens: int | None = Field(
        default=None,
        description=("Total input tokens (incl. cached and non-cached) for this step."),
    )
    completion_tokens: int | None = Field(
        default=None, description="Total tokens generated by the LLM for this step."
    )
    cached_tokens: int | None = Field(
        default=None, description="Subset of prompt_tokens served from cache."
    )
    cost_usd: float | None = Field(default=None, description="Monetary cost of this step in USD.")
    prompt_token_ids: list[int] | None = Field(
        default=None, description="Token ids for the prompt (length == prompt_tokens)."
    )
    completion_token_ids: list[int] | None = Field(
        default=None,
        description="Token ids for the completion (length == completion_tokens).",
    )
    logprobs: list[float] | None = Field(
        default=None, description="Log probabilities aligned with completion_token_ids."
    )
    extra: dict[str, Any] | None = Field(
        default=None,
        description="Provider-specific metrics (e.g. reasoning_tokens, cache_creation_input_tokens).",
    )


class FinalMetricsSchema(BaseModel):
    """Trajectory-aggregate metrics (spec §II FinalMetricsSchema). All optional."""

    model_config = ConfigDict(extra="forbid")

    total_prompt_tokens: int | None = None
    total_completion_tokens: int | None = None
    total_cached_tokens: int | None = None
    total_cost_usd: float | None = None
    total_steps: int | None = None
    extra: dict[str, Any] | None = None


# ---------------------------------------------------------------------------
# Tool-call + observation schemas
# ---------------------------------------------------------------------------


class ToolCallSchema(BaseModel):
    """A single tool invocation by the agent (spec §II ToolCallSchema)."""

    model_config = ConfigDict(extra="forbid")

    tool_call_id: str = Field(
        description="Unique id; joins to ObservationResultSchema.source_call_id."
    )
    function_name: str = Field(description="Name of the tool/function invoked.")
    arguments: dict[str, Any] = Field(description="Arguments JSON object (may be empty).")
    extra: dict[str, Any] | None = Field(
        default=None, description="Custom tool-call metadata (v1.7)."
    )


class SubagentTrajectoryRef(BaseModel):
    """Reference to a delegated subagent trajectory (spec §II SubagentTrajectoryRefSchema)."""

    model_config = ConfigDict(extra="forbid")

    trajectory_id: str | None = Field(
        default=None,
        description=(
            "Canonical id for an embedded subagent trajectory; resolves "
            "against root.subagent_trajectories[].trajectory_id (v1.7)."
        ),
    )
    trajectory_path: str | None = Field(
        default=None,
        description="External-file reference (path, URL, DB ref) to a subagent trajectory.",
    )
    session_id: str | None = Field(
        default=None,
        description=(
            "Run-scoped session id of the subagent. **Informational only** in v1.7 — "
            "NOT a resolution key (see spec §II)."
        ),
    )
    extra: dict[str, Any] | None = None

    @model_validator(mode="after")
    def _check_at_least_one_resolver(self) -> SubagentTrajectoryRef:
        if self.trajectory_id is None and self.trajectory_path is None:
            raise ValueError(
                "SubagentTrajectoryRef MUST set at least one of "
                "trajectory_id (embedded) or trajectory_path (external) "
                "(spec §II v1.7)."
            )
        return self


class ObservationResultSchema(BaseModel):
    """One result entry within an Observation (spec §II ObservationResultSchema)."""

    model_config = ConfigDict(extra="forbid")

    source_call_id: str | None = Field(
        default=None,
        description=(
            "Joins back to ToolCallSchema.tool_call_id in the same step. "
            "Null when the result has no associated tool call."
        ),
    )
    content: str | list[ContentPart] | None = Field(
        default=None,
        description=(
            "Tool/action output. Text-only (string) or multimodal "
            "(list[ContentPart], v1.6+). MAY be omitted if "
            "subagent_trajectory_ref is set."
        ),
    )
    subagent_trajectory_ref: list[SubagentTrajectoryRef] | None = Field(
        default=None,
        description="References to delegated subagent trajectories.",
    )
    extra: dict[str, Any] | None = None


class ObservationSchema(BaseModel):
    """Wrapper around the results array (spec §II ObservationSchema)."""

    model_config = ConfigDict(extra="forbid")

    results: list[ObservationResultSchema] = Field(
        description="Array of result entries (one per tool call or action)."
    )


